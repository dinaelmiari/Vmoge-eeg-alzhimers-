def compute_spectral_metrics(X_real_ad, X_synth):
    """Fréchet Distance + theta/alpha bias + Cohen's d."""
    freqs = np.fft.rfftfreq(N_SAMPLES, d=1.0 / SFREQ)
    BANDS = {'delta':(0.5,4),'theta':(4,8),'alpha':(8,13),'beta':(13,30),'gamma':(30,40)}

    def bp(X, lo, hi, n_max=200):
        mask = (freqs >= lo) & (freqs < hi)
        return np.array([
            np.mean([np.log1p((np.abs(np.fft.rfft(ep[ch]))**2)[mask].mean())
                     for ch in range(N_CHANNELS)])
            for ep in X[:n_max]])

    def tar(X, n_max=200):
        ratios = []
        for ep in X[:n_max]:
            r = []
            for ch in range(N_CHANNELS):
                psd   = np.abs(np.fft.rfft(ep[ch]))**2
                t_val = psd[(freqs >= 4) & (freqs < 8)].mean()
                a_val = psd[(freqs >= 8) & (freqs < 13)].mean()
                r.append(t_val / (a_val + 1e-10))
            ratios.append(np.mean(r))
        return np.array(ratios)

    def featurise(X, n_max=150):
        return np.array([
            [np.log1p(np.mean([np.log1p((np.abs(np.fft.rfft(ep[ch]))**2)
             [(freqs >= lo) & (freqs < hi)].mean())
             for ch in range(N_CHANNELS)])) for _, (lo, hi) in BANDS.items()]
            for ep in X[:n_max]], dtype=np.float32)

    def frechet(fr, fs):
        mr, ms = fr.mean(0), fs.mean(0)
        reg    = np.eye(fr.shape[1]) * 1e-4
        cr     = np.cov(fr, rowvar=False) + reg
        cs     = np.cov(fs, rowvar=False) + reg
        cm     = sqrtm(cr @ cs)
        if np.iscomplexobj(cm): cm = cm.real
        return max(float(np.real((mr-ms)@(mr-ms) + np.trace(cr+cs-2*cm))), 0.0)

    tar_r, tar_s   = tar(X_real_ad), tar(X_synth)
    feat_r, feat_s = featurise(X_real_ad), featurise(X_synth)
    fd             = frechet(feat_r, feat_s)

    log.info("  PSD comparison (real AD vs synthetic):")
    for band, (lo, hi) in BANDS.items():
        r = bp(X_real_ad, lo, hi).mean()
        s = bp(X_synth,   lo, hi).mean()
        err = 100.0 * (s - r) / (abs(r) + 1e-8)
        flag = "  ← HIGH" if abs(err) > 20 else ""
        log.info(f"    {band:5s}: real={r:.3f}  synth={s:.3f}  err={err:+.1f}%{flag}")

    return {
        'frechet':      fd,
        'tar_bias':     float(100.0*(tar_s.mean()-tar_r.mean())/(abs(tar_r.mean())+1e-8)),
        'ad_direction': bool(tar_s.mean() > tar_r.mean()),
    }


def evaluate_with_fn_profile(model, X_te, y_te):
    """Evaluate + profile False Negative epochs by theta/alpha and delta power."""
    y_pred, y_prob = predict(model, X_te)
    metrics = compute_metrics(y_te, y_pred, y_prob)

    if metrics['fn'] > 0:
        fn_idx = np.where((y_pred == 0) & (y_te == 1))[0]
        tp_idx = np.where((y_pred == 1) & (y_te == 1))[0]
        pct    = 100 * metrics['fn'] / max(metrics['fn'] + metrics['tp'], 1)
        log.warning(f"  [FN] {metrics['fn']} AD epochs misclassified as HC ({pct:.1f}%)")

        freqs = np.fft.rfftfreq(N_SAMPLES, d=1.0 / SFREQ)

        def band_power(idx_list, lo, hi):
            mask = (freqs >= lo) & (freqs < hi)
            vals = []
            for idx in idx_list[:100]:
                psd = np.abs(np.fft.rfft(X_te[idx], axis=-1)).mean(0) ** 2
                vals.append(np.log1p(psd[mask].mean()))
            return float(np.mean(vals)) if vals else float('nan')

        fn_theta = band_power(fn_idx, 4, 8);  fn_alpha = band_power(fn_idx, 8, 13)
        fn_delta = band_power(fn_idx, 0.5, 4); fn_ta   = fn_theta / (fn_alpha + 1e-8)
        log.info(f"   ├─ Missed AD:  delta={fn_delta:.3f}  theta={fn_theta:.3f}  "
                 f"alpha={fn_alpha:.3f}  θ/α={fn_ta:.3f}")

        if len(tp_idx) > 0:
            tp_theta = band_power(tp_idx, 4, 8); tp_alpha = band_power(tp_idx, 8, 13)
            tp_delta = band_power(tp_idx, 0.5, 4); tp_ta  = tp_theta / (tp_alpha + 1e-8)
            log.info(f"   ├─ Caught AD:  delta={tp_delta:.3f}  theta={tp_theta:.3f}  "
                     f"alpha={tp_alpha:.3f}  θ/α={tp_ta:.3f}")
            if fn_ta < tp_ta * 0.85:
                log.info("   └─ WHY: Missed AD has weaker theta/alpha slowing "
                         "(likely mild/early-stage or high individual variability)")
            elif fn_delta < tp_delta * 0.85:
                log.info("   └─ WHY: Missed AD has low delta power "
                         "(possible medication effect or atypical subtype)")
            else:
                log.info("   └─ WHY: No dominant spectral difference — failure may be "
                         "spatial/channel-level rather than global frequency content")

    return metrics, y_pred, y_prob

