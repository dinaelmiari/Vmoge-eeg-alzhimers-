def train_eegnet(X_tr, y_tr, X_val, y_val, seed=42):
    """
    Train EEGNet with:
    - Focal Loss (Lin et al. 2017) 
    - Stronger AD class weight (AD_WEIGHT_MULTIPLIER=3) 
    - Early stopping on validation loss


    """
    torch.manual_seed(seed)
    model  = EEGNet().to(DEVICE)
    counts = np.bincount(y_tr)
    # Balanced weight then boosted by AD_WEIGHT_MULTIPLIER
    w_balanced = len(y_tr) / (len(counts) * counts)
    w_balanced[1] *= AD_WEIGHT_MULTIPLIER    # boost AD class weight
    cw = torch.FloatTensor(w_balanced).to(DEVICE)
    log.info(f"  EEGNet weights → HC:{cw[0]:.3f}  AD:{cw[1]:.3f}  "
             f"(focal={'on' if USE_FOCAL_LOSS else 'off'} γ={FOCAL_GAMMA})")

    criterion = FocalLoss(weight=cw, gamma=FOCAL_GAMMA) if USE_FOCAL_LOSS \
                else nn.CrossEntropyLoss(weight=cw)

    opt   = optim.Adam(model.parameters(), lr=EEGNET_LR, weight_decay=1e-4)
    sched = optim.lr_scheduler.CosineAnnealingLR(opt, EEGNET_EPOCHS, 1e-5)

    loader_tr  = make_weighted_loader(X_tr,  y_tr,  EEGNET_BATCH, shuffle=True)
    loader_val = make_weighted_loader(X_val, y_val, EEGNET_BATCH, shuffle=False)

    best_val, best_state, no_imp = float('inf'), None, 0

    for epoch in range(EEGNET_EPOCHS):
        model.train()
        for Xb, yb in loader_tr:
            Xb, yb = Xb.to(DEVICE), yb.to(DEVICE)
            opt.zero_grad()
            criterion(model(Xb), yb).backward()
            opt.step()
        sched.step()

        model.eval()
        vl = 0.0
        with torch.no_grad():
            for Xb, yb in loader_val:
                vl += F.cross_entropy(   # always use CE for val monitoring
                    model(Xb.to(DEVICE)), yb.to(DEVICE), weight=cw).item()
        vl /= len(loader_val)

        if vl < best_val - 1e-4:
            best_val, no_imp = vl, 0
            best_state = {k: v.clone() for k, v in model.state_dict().items()}
        else:
            no_imp += 1
            if no_imp >= EEGNET_PATIENCE:
                log.info(f"  EEGNet early stop at epoch {epoch+1}")
                break

    model.load_state_dict(best_state)
    return model

