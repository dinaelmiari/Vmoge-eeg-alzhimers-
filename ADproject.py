HANNING = np.hanning(N_SAMPLES)

def signed_log(x):
    return np.sign(x) * np.log1p(np.abs(x))

def inv_signed_log(x):
    return np.sign(x) * np.expm1(np.abs(x))

def eeg_to_complex_spectrum(X):
    """
    (N, 19, 1000) → clin (N, 2, 19, 80), full (N, 2, 19, 501)
    Hanning window → rfft → signed-log transform.
    This is the exact function from the working reference.
    """
    N        = len(X)
    clin_out = np.zeros((N, 2, N_CHANNELS, N_FREQ_CLIN), dtype=np.float32)
    full_out = np.zeros((N, 2, N_CHANNELS, N_RFFT),      dtype=np.float32)
    for i, epoch in enumerate(X):
        fft_c           = np.fft.rfft(epoch * HANNING, axis=-1)
        real_sl         = signed_log(fft_c.real)
        imag_sl         = signed_log(fft_c.imag)
        full_out[i, 0]  = real_sl
        full_out[i, 1]  = imag_sl
        clin_out[i, 0]  = real_sl[:, FREQ_MASK]
        clin_out[i, 1]  = imag_sl[:, FREQ_MASK]
    return clin_out, full_out

def complex_spectrum_to_eeg(spec_full_norm, spec_mean, spec_std):
    """
    (N, 2, 19, 501) normalised → (N, 19, 1000) time-domain EEG.
    Exact irfft reconstruction — no phase pooling.
    """
    spec    = spec_full_norm * spec_std + spec_mean
    real_pt = inv_signed_log(spec[:, 0])
    imag_pt = inv_signed_log(spec[:, 1])
    eeg     = np.fft.irfft(real_pt + 1j * imag_pt, n=N_SAMPLES, axis=-1)
    for i in range(len(eeg)):
        s = eeg[i].std() + 1e-10
        eeg[i] = (eeg[i] - eeg[i].mean()) / s
    return eeg.astype(np.float32)

