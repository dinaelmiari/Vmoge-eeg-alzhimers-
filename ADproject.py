class FocalLoss(nn.Module):
    """
    Focal Loss: FL(p_t) = -(1 - p_t)^gamma * log(p_t)
    gamma=0 reduces to standard cross-entropy.
    gamma=2 (default) strongly down-weights easy examples.

    Combined with class weights to handle the 29:15 HC:AD imbalance.
    Reference: Lin et al. (2017) "Focal Loss for Dense Object Detection". ICCV.
    """
    def __init__(self, weight=None, gamma=FOCAL_GAMMA):
        super().__init__()
        self.weight = weight
        self.gamma  = gamma

    def forward(self, logits, targets):
        ce_loss = F.cross_entropy(logits, targets,
                                   weight=self.weight, reduction='none')
        pt      = torch.exp(-ce_loss)                    # probability of true class
        focal   = ((1.0 - pt) ** self.gamma) * ce_loss   # focal weight × CE
        return focal.mean()

