@torch.no_grad()
def generate_synthetic_ad(encoder, diff_dec, full_mean, full_std,
                            Z_ad, sigma_ad, n_samples):
    """
    Generate synthetic AD EEG using DDIM in full complex spectral space.
    This keeps z near the real AD manifold, preventing incoherent generation.
    Reference: Song et al. (2021) DDIM; Rombach et al. (2022) LDM.
    """
    encoder.eval(); diff_dec.eval()
    step_idx = torch.linspace(0, DDPM_T - 1, DDIM_STEPS + 1).long().flip(0)
    all_spec = []

    for i in range(0, n_samples, 50):
        n_this = min(50, n_samples - i)

        # Sample z: pick real AD codes + per-dimension perturbation
        idx    = np.random.randint(0, len(Z_ad), n_this)
        z_samp = Z_ad[idx] + LATENT_NOISE * sigma_ad * np.random.randn(n_this, LATENT_DIM)
        z_samp = np.clip(z_samp, -1.0, 1.0)
        z_t    = torch.FloatTensor(z_samp).to(DEVICE)

        x = torch.randn(n_this, 2, N_CHANNELS, N_RFFT, device=DEVICE)

        for j in range(DDIM_STEPS):
            t_now  = step_idx[j].to(DEVICE).expand(n_this)
            t_next = step_idx[j + 1]
            np_    = diff_dec(x, t_now, z_t)
            ab_now = SCHEDULE['alpha_bars'][step_idx[j]]
            ab_nxt = (SCHEDULE['alpha_bars'][t_next]
                      if t_next >= 0 else torch.tensor(1.0).to(DEVICE))
            x0p    = ((x - (1 - ab_now).sqrt() * np_) / ab_now.sqrt()).clamp(-4, 4)
            x      = ab_nxt.sqrt() * x0p + (1 - ab_nxt).sqrt() * np_

        all_spec.append(x.cpu().numpy())

    spec_norm = np.concatenate(all_spec)
    return complex_spectrum_to_eeg(spec_norm, full_mean, full_std)

