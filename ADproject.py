def train_vmoge(X_ad_fold, X_all_fold, y_all_fold, seed=42):
    """
    Two-phase VMoGE training — restored to the working reference.

    Phase 1 (warm-up):
      Train encoder + rec_dec on ALL training subjects (HC + AD).


    Phase 2 (joint):
      Train encoder + diff_dec on AD epochs only.
      Diffusion decoder learns to generate AD spectra conditioned on z.

    Returns: encoder, diff_dec, full_mean, full_std, Z_ad, sigma_ad
    """
    torch.manual_seed(seed)

    log.info("    Computing spectral representations...")
    clin_all, full_all = eeg_to_complex_spectrum(X_all_fold)
    clin_ad,  full_ad  = eeg_to_complex_spectrum(X_ad_fold)

    # Normalise using this fold's training statistics only (no test leakage)
    clin_mean = clin_all.mean(); clin_std = clin_all.std() + 1e-10
    full_mean = full_all.mean(); full_std = full_all.std() + 1e-10

    clin_all_norm = (clin_all - clin_mean) / clin_std
    clin_ad_norm  = (clin_ad  - clin_mean) / clin_std
    full_ad_norm  = (full_ad  - full_mean) / full_std

    encoder  = VMoGE_Encoder().to(DEVICE)
    rec_dec  = ComplexRecDecoder().to(DEVICE)
    diff_dec = SpectralDiffDecoder().to(DEVICE)

    # ── Phase 1: Warm-up on ALL subjects ─────────────────────────────────────
    log.info(f"    Phase 1: Encoder warm-up ({WARMUP_EPOCHS} epochs, ALL subjects)...")
    w       = 1.0 / np.bincount(y_all_fold)[y_all_fold]
    sampler = WeightedRandomSampler(torch.FloatTensor(w), len(w), True)
    clin_t  = torch.FloatTensor(clin_all_norm)
    loader_w = DataLoader(TensorDataset(clin_t, clin_t),
                          VMOGE_BATCH, sampler=sampler, drop_last=True)

    opt_w = optim.AdamW(list(encoder.parameters()) + list(rec_dec.parameters()),
                         lr=VMOGE_LR, weight_decay=1e-4)
    sch_w = optim.lr_scheduler.CosineAnnealingLR(opt_w, WARMUP_EPOCHS, 1e-6)

    for epoch in range(WARMUP_EPOCHS):
        encoder.train(); rec_dec.train()
        for spec_b, tgt_b in loader_w:
            spec_b, tgt_b = spec_b.to(DEVICE), tgt_b.to(DEVICE)
            z    = encoder(spec_b, ADJ)
            loss = F.mse_loss(rec_dec(z), tgt_b)
            opt_w.zero_grad(); loss.backward()
            nn.utils.clip_grad_norm_(
                list(encoder.parameters()) + list(rec_dec.parameters()), 1.0)
            opt_w.step()
        sch_w.step()
        if (epoch + 1) % 20 == 0:
            log.info(f"      Warm-up {epoch+1}/{WARMUP_EPOCHS} | loss={loss.item():.5f}")

    # ── Phase 2: Joint training on AD only ───────────────────────────────────
    log.info(f"    Phase 2: Joint training ({JOINT_EPOCHS} epochs, AD only)...")
    loader_ad = DataLoader(
        TensorDataset(torch.FloatTensor(clin_ad_norm),
                      torch.FloatTensor(full_ad_norm)),
        VMOGE_BATCH, shuffle=True, drop_last=True)

    opt_j = optim.AdamW(list(encoder.parameters()) + list(diff_dec.parameters()),
                         lr=VMOGE_LR, weight_decay=1e-4)
    sch_j = optim.lr_scheduler.CosineAnnealingLR(opt_j, JOINT_EPOCHS, 1e-6)
    rec_dec.eval()

    for epoch in range(JOINT_EPOCHS):
        encoder.train(); diff_dec.train()
        for clin_b, full_b in loader_ad:
            clin_b, full_b = clin_b.to(DEVICE), full_b.to(DEVICE)
            z         = encoder(clin_b, ADJ)
            t_idx     = torch.randint(0, DDPM_T, (clin_b.size(0),), device=DEVICE)
            x_n, eps  = add_noise_4d(full_b, t_idx, SCHEDULE)
            loss_diff = F.mse_loss(diff_dec(x_n, t_idx, z), eps)
            with torch.no_grad():
                loss_rec = F.mse_loss(rec_dec(z.detach()), clin_b) * LAMBDA_REC
            loss = loss_diff + loss_rec
            opt_j.zero_grad(); loss.backward()
            nn.utils.clip_grad_norm_(
                list(encoder.parameters()) + list(diff_dec.parameters()), 1.0)
            opt_j.step()
        sch_j.step()
        if (epoch + 1) % 50 == 0:
            log.info(f"      Joint {epoch+1}/{JOINT_EPOCHS} | "
                     f"diff={loss_diff.item():.5f} | rec={loss_rec.item():.5f}")

    # ── Fit AD latent distribution (for z-sampling in generation) ────────────
    encoder.eval()
    all_z = []
    with torch.no_grad():
        for i in range(0, len(clin_ad_norm), 64):
            b = torch.FloatTensor(clin_ad_norm[i:i+64]).to(DEVICE)
            all_z.append(encoder(b, ADJ).cpu().numpy())
    Z_ad     = np.concatenate(all_z)        # (N_ad, 128) — real AD latent codes
    sigma_ad = Z_ad.std(0)                  # (128,) — per-dimension std

    log.info(f"    Z_ad shape: {Z_ad.shape} | sigma_ad mean: {sigma_ad.mean():.4f}")
    return encoder, diff_dec, full_mean, full_std, Z_ad, sigma_ad

