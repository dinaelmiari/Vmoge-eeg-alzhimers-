class EEGNet(nn.Module):
    def __init__(self, n_ch=N_CHANNELS, n_t=N_SAMPLES, dropout=EEGNET_DROPOUT):
        super().__init__()
        F1=8; D=2; F2=16
        self.block1 = nn.Sequential(
            nn.Conv2d(1, F1, (1, 64), padding=(0, 32), bias=False),
            nn.BatchNorm2d(F1),
            nn.Conv2d(F1, F1*D, (n_ch, 1), groups=F1, bias=False),
            nn.BatchNorm2d(F1*D), nn.ELU(),
            nn.AvgPool2d((1, 4)), nn.Dropout(dropout))
        self.block2 = nn.Sequential(
            nn.Conv2d(F1*D, F1*D, (1, 16), padding=(0, 8), groups=F1*D, bias=False),
            nn.Conv2d(F1*D, F2, (1, 1), bias=False),
            nn.BatchNorm2d(F2), nn.ELU(),
            nn.AvgPool2d((1, 8)), nn.Dropout(dropout))
        with torch.no_grad():
            self._flat = self.block2(
                self.block1(torch.zeros(1, 1, n_ch, n_t))).numel()
        self.fc = nn.Sequential(nn.Flatten(), nn.Linear(self._flat, 2))

    def forward(self, x):
        return self.fc(self.block2(self.block1(x)))


# ── VMoGE Encoder — restored from working reference ──────────────────────────

class GraphConvLayer(nn.Module):
    def __init__(self, in_f, out_f):
        super().__init__()
        self.W = nn.Linear(in_f, out_f, bias=True)
    def forward(self, H, A):
        return F.relu(self.W(torch.bmm(
            A.unsqueeze(0).expand(H.size(0), -1, -1), H)))


class ThreeLayerGCN(nn.Module):
    """
    3 GCN layers with residual connections.
    3 hops = reaches fronto-parietal connectivity (disrupted in AD).
    Residual connections prevent over-smoothing.
    Reference: Kipf & Welling (2017); Li et al. (2018)
    """
    def __init__(self, in_f, hidden=32, out_f=32):
        super().__init__()
        self.l1 = GraphConvLayer(in_f,   hidden)
        self.l2 = GraphConvLayer(hidden, hidden)
        self.l3 = GraphConvLayer(hidden, out_f)
        self.r1 = nn.Linear(in_f, hidden, bias=False) if in_f != hidden else nn.Identity()
        self.r3 = nn.Linear(hidden, out_f, bias=False) if hidden != out_f else nn.Identity()

    def forward(self, H, A):
        H1 = self.l1(H,  A) + self.r1(H)
        H2 = self.l2(H1, A) + H1
        H3 = self.l3(H2, A) + self.r3(H2)
        return H3


class SpectralFreqExpert(nn.Module):
    """
    Frequency-band expert: Conv1d over the 80 frequency bins,
    then 3-layer GCN over the 19 EEG channel nodes.
    kernels [32,16,8,4] → experts specialise broadband→narrowband.
    """
    def __init__(self, kernel, out_f=32):
        super().__init__()
        self.freq_conv = nn.Sequential(
            nn.Conv1d(2, 16, kernel_size=kernel, padding=kernel//2, bias=False),
            nn.BatchNorm1d(16), nn.ELU(),
            nn.AdaptiveAvgPool1d(16))      # → (B*19, 16, 16)
        self.gcn = ThreeLayerGCN(16 * 16, 32, out_f)

    def forward(self, spec, adj):
        B, C, Nch, Nf = spec.shape        # (B, 2, 19, 80)
        x = spec.permute(0, 2, 1, 3).reshape(B * Nch, C, Nf)  # (B*19, 2, 80)
        h = self.freq_conv(x)             # (B*19, 16, 16)
        h = h.view(B, Nch, -1)           # (B, 19, 256)
        return self.gcn(h, adj)           # (B, 19, out_f)


class GatingNetwork(nn.Module):
    def __init__(self, n_exp=4):
        super().__init__()
        self.net = nn.Sequential(
            nn.AdaptiveAvgPool2d(1), nn.Flatten(),
            nn.Linear(2, 16), nn.ReLU(),
            nn.Linear(16, n_exp), nn.Softmax(dim=-1))
    def forward(self, spec):
        return self.net(spec)


class VMoGE_Encoder(nn.Module):
    """
    VMoGE Encoder v5 — restored to working reference.
    Input:  (B, 2, 19, 80) — 2-channel clinical complex spectrum
    Output: z (B, 128)     — deterministic latent vector
    """
    KERNELS = [32, 16, 8, 4]

    def __init__(self, latent_dim=LATENT_DIM):
        super().__init__()
        self.experts = nn.ModuleList([SpectralFreqExpert(k) for k in self.KERNELS])
        self.gate    = GatingNetwork(4)
        self.fc_z    = nn.Sequential(
            nn.Linear(N_CHANNELS * 32, 256), nn.LayerNorm(256), nn.GELU(),
            nn.Dropout(0.1),
            nn.Linear(256, latent_dim), nn.Tanh())

    def forward(self, spec, adj):
        w    = self.gate(spec)
        outs = [e(spec, adj) for e in self.experts]
        comb = sum(w[:, i].view(-1, 1, 1) * outs[i] for i in range(4))
        return self.fc_z(comb.flatten(1))


