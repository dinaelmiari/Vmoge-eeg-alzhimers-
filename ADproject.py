def spectral_bias_correction(X_synth, X_real_ad):
    """
    Rescale synthetic EEG so its per-band log power matches the real AD
    training distribution.

    This is a soft spectral matching — it corrects the overall level of
    each band without destroying the inter-epoch variability.

    Parameters
    ----------
    X_synth   : (N_synth, 19, 1000) synthetic EEG
    X_real_ad : (N_ad,    19, 1000) real AD training EEG

    Returns
    -------
    X_corrected : (N_synth, 19, 1000) spectrally corrected synthetic EEG
    correction_log : dict of per-band correction factors applied
    """
    freqs = np.fft.rfftfreq(N_SAMPLES, d=1.0 / SFREQ)
    BANDS_CORR = {
        'delta': (0.5,  4.0),
        'theta': (4.0,  8.0),
        'alpha': (8.0, 13.0),
        'beta':  (13.0,30.0),
        'gamma': (30.0,40.0),
    }

    def mean_log_band_power(X, lo, hi, n_max=300):
        mask = (freqs >= lo) & (freqs < hi)
        vals = []
        for ep in X[:n_max]:
            psd = np.abs(np.fft.rfft(ep, axis=-1)) ** 2   # (19, 501)
            vals.append(np.log1p(psd[:, mask].mean()))
        return float(np.mean(vals))

    # Compute target (real) and current (synthetic) band power levels
    log.info("  Spectral bias correction:")
    band_corrections = {}
    for band, (lo, hi) in BANDS_CORR.items():
        p_real  = mean_log_band_power(X_real_ad, lo, hi)
        p_synth = mean_log_band_power(X_synth,   lo, hi)
        # Correction factor in linear power space
        correction = np.exp(p_real - p_synth)   # if synth too high, factor < 1
        band_corrections[band] = (lo, hi, float(correction))
        err_before = 100.0 * (p_synth - p_real) / (abs(p_real) + 1e-8)
        log.info(f"    {band:5s}: error={err_before:+.1f}%  correction_factor={correction:.4f}")

    # Apply correction in frequency domain
    X_corrected = np.zeros_like(X_synth)
    for i, epoch in enumerate(X_synth):
        fft_ep = np.fft.rfft(epoch, axis=-1)   # (19, 501) complex
        for band, (lo, hi, factor) in band_corrections.items():
            mask = (freqs >= lo) & (freqs < hi)
            fft_ep[:, mask] *= np.sqrt(factor)  # sqrt because power = |fft|^2
        corrected = np.fft.irfft(fft_ep, n=N_SAMPLES, axis=-1)
        # Re-normalise
        s = corrected.std() + 1e-10
        X_corrected[i] = (corrected - corrected.mean()) / s

    return X_corrected.astype(np.float32), band_corrections

