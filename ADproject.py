# ── Spectral diffusion decoder (2D UNet) ─────────────────────────────────────
class SinEmbed(nn.Module):
    def __init__(self, dim=128):
        super().__init__()
        self.dim = dim
    def forward(self, t):
        half  = self.dim // 2
        freqs = torch.exp(-np.log(10000) * torch.arange(half, device=t.device) / half)
        ang   = t.float().unsqueeze(1) * freqs.unsqueeze(0)
        return torch.cat([torch.sin(ang), torch.cos(ang)], 1)


class SpectralResBlock(nn.Module):
    def __init__(self, ch, t_dim=128, z_dim=LATENT_DIM):
        super().__init__()
        self.c1  = nn.Conv2d(ch, ch, 3, padding=1)
        self.c2  = nn.Conv2d(ch, ch, 3, padding=1)
        self.n1  = nn.GroupNorm(min(8, ch), ch)
        self.n2  = nn.GroupNorm(min(8, ch), ch)
        self.act = nn.SiLU()
        self.tp  = nn.Linear(t_dim, ch)
        self.zp  = nn.Linear(z_dim, ch)
    def forward(self, x, te, z):
        h = self.act(self.n1(self.c1(x)))
        h = h + self.tp(te).unsqueeze(-1).unsqueeze(-1)
        h = h + self.zp(z).unsqueeze(-1).unsqueeze(-1)
        return x + self.act(self.n2(self.c2(h)))


class SpectralDiffDecoder(nn.Module):
    """
    2D UNet DDPM decoder.
    Input:  (B, 2, 19, 501) noisy full spectrum + timestep t + z
    Output: (B, 2, 19, 501) predicted noise
    """
    def __init__(self, in_ch=2, t_dim=128, z_dim=LATENT_DIM):
        super().__init__()
        self.te  = SinEmbed(t_dim)
        self.tmp = nn.Sequential(nn.Linear(t_dim, t_dim*2), nn.SiLU(),
                                  nn.Linear(t_dim*2, t_dim))
        self.inc = nn.Conv2d(in_ch, 32, 3, padding=1)
        self.e1  = SpectralResBlock(32)
        self.d1  = nn.Conv2d(32, 64, (1, 4), stride=(1, 2), padding=(0, 1))
        self.e2  = SpectralResBlock(64)
        self.d2  = nn.Conv2d(64, 128, (1, 4), stride=(1, 2), padding=(0, 1))
        self.mid = SpectralResBlock(128)
        self.u2  = nn.ConvTranspose2d(128, 64, (1, 4), stride=(1, 2), padding=(0, 1))
        self.de2 = SpectralResBlock(128)
        self.u1  = nn.ConvTranspose2d(128, 32, (1, 4), stride=(1, 2), padding=(0, 1))
        self.de1 = SpectralResBlock(64)
        self.out = nn.Sequential(nn.GroupNorm(8, 64), nn.SiLU(), nn.Conv2d(64, in_ch, 1))

    def forward(self, x, t, z):
        te = self.tmp(self.te(t))
        x  = self.inc(x)
        e1 = self.e1(x,  te, z); x = self.d1(e1)
        e2 = self.e2(x,  te, z); x = self.d2(e2)
        x  = self.mid(x, te, z)
        x  = self.u2(x)
        h, w = min(x.shape[2], e2.shape[2]), min(x.shape[3], e2.shape[3])
        x  = self.de2(torch.cat([x[:,:,:h,:w], e2[:,:,:h,:w]], 1), te, z)
        x  = self.u1(x)
        h, w = min(x.shape[2], e1.shape[2]), min(x.shape[3], e1.shape[3])
        x  = self.de1(torch.cat([x[:,:,:h,:w], e1[:,:,:h,:w]], 1), te, z)
        x  = F.interpolate(x, size=(N_CHANNELS, N_RFFT), mode='bilinear', align_corners=False)
        return self.out(x)

